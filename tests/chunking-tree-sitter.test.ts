describe('tree-sitter chunking', () => {
  test('keeps top-level TypeScript declarations intact when possible', async () => {
    const chunks = await chunkTextDocument({
      filePath: 'src/example.ts',
      content: [
        'export function firstFeature() {',
        '  const label = "first";',
        '  return label.repeat(2);',
        '}',
        '',
        'export function secondFeature() {',
        '  const label = "second";',
        '  return label.repeat(3);',
        '}',
      ].join('\n'),
      config,
    });

    expect(chunks.length).toBe(2);
    expect(chunks[0]?.content).toContain('function firstFeature');
    expect(chunks[0]?.content).not.toContain('function secondFeature');
    expect(chunks[1]?.content).toContain('function secondFeature');
  });
});
